const router = require("express").Router();
const authenticate = require("../../middleware/authenticate");
const authorizeRoles = require("../../middleware/authorize");
const validate = require("../../middleware/validate");
const { USER_ROLES } = require("../../constants/roles");
const { reportQueryValidation, dateRangeValidation, technicianPerformanceValidation, slaReportValidation, categoryReportValidation } = require("./reports.validation");
const { getTicketReport, getDateRangeReport, getTechnicianPerformanceReport, getSlaReport, getCategoryReport } = require("./reports.controller");
router.use(authenticate, authorizeRoles(USER_ROLES.ADMIN));
router.get("/tickets", reportQueryValidation(), validate, getTicketReport);
router.get("/date-range", dateRangeValidation, validate, getDateRangeReport);
router.get("/technician-performance", technicianPerformanceValidation, validate, getTechnicianPerformanceReport);
router.get("/sla", slaReportValidation, validate, getSlaReport);
router.get("/categories", categoryReportValidation, validate, getCategoryReport);
module.exports = router;
